; Scene placement tables: the index of 97 scenes and the 97 actor lists it points to (file offsets 39348-43485, SNES $01:99B4-$A9DD, bank 00; 389 + 3749 bytes).
; 
; === MODEL ===
; SpawnSceneActors scans ScenePlacementIndex for the first 4-byte row whose area and scene equal area_current and scene_current (a first byte of $80 or more ends the scan) and hands the row's list to SpawnPlacementList. A scene is one row; the 97 rows are exactly the 97 scenes of the scene profile list (lib_scene_profile_data) and of the asset list (SceneAssetLists, minus its dummy first record).
; 
; === ROWS ===
; Index row (4 bytes): +0 area, +1 scene, +2 word &list. List row (4 bytes): +0 x tile, +1 y tile, +2 flags byte (bits 7 and 6 flip Y and X; bit 0 is passed to $1C as $0100), +3 meta type (WorldMetaPointers). Position = x tile x 16, y tile x 16 + 16. A list ends with a byte of $FF. The first row of every list is the hero (meta type 0): its tile is the start position of the scene when no warp_dest is set.
; 913 rows in all (97 hero rows and 816 actors); the longest list is PlacementA06S01 with 33 rows. The lists are named PlacementAaaSss after the (area, scene) of their index row, both in hex: PlacementA05S02 is area 5, scene 2.
; 
; === AREAS ===
; 22 areas ($00-$15) with 13, 4, 3, 6, 6, 10, 1, 5, 4, 2, 1, 7, 3, 5, 5, 2, 1, 4, 7, 3, 3 and 2 scenes. docs/areas-and-scenes.md names them and maps (area, scene) to the location_id used by the chest, exit and plate lists.
; 
; === NOTES ===
; - Lair monsters are not listed here: they come from LairRecords (the lair actor spawns them), so the 'enemies' of a scene are the placement list plus the lairs of its location.
; - structs.json names the index row unk1 and the list row unk2; the 97 lists keep the unk2 type with the delimiter $FF.
---------------------------------------------

