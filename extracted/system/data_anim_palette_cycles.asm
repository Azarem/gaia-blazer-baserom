; Animation bank $0D: colour animations, 80 lists of 6-byte copy steps (file offsets 425984-440319, SNES $0D:8000-$B7FF, bank 06; 14336 bytes).
; 
; === MODEL ===
; Not sprite animations: the lists are read by the record stepper of lib_animation (COPs 92-95, 9D, 9E) which copies bytes into WRAM bank $7F. A step is 6 bytes: +0 hold count (0 ends the list), +1 word source address (in this bank), +3 destination colour (x 2 = the offset in the CGRAM shadow $7F0000), +4 length - 1, +5 delay. The data fit palette cycling: the source blocks are runs of BGR555 words, and consecutive steps rotate the same colours by one position (for example the leaf at $0680C5 is E749 2B52 8F5E 3273 ..., the next one 2B52 E749 2B52 8F5E ...), written to the same colour index ($71 in that list) every time. Length - 1 is always odd (whole colours) except $02: the 53 steps with destination $00 and 3 bytes ($20 $40 $80 and similar triples) write the three COLDATA bytes of the fixed colour (lib_animation: coldata_buffer at $7F0200), a colour fade of the backdrop.
; Destination colours in use include $21, $31, $51, $71, $58, $57, $70, $A1, $91, $81; lengths 3 to 30 bytes (up to 15 colours); hold counts are mostly 1 (614 of 686 steps); delays 0-13 frames. 80 lists, 686 steps, 593 leaves.
; 69 meta entries (WorldMetaPointers: mostly the types $01-$0F of every world, none of the enemies) use this bank as their animation table, so each is an actor whose 'animation' is a colour cycle; which scene effect each one runs was not traced. FM-A4 and FM-A11 called the lists 'VRAM copy lists'; the destination and the data say colours (OQ-I033-6, a DISCREPANCY with the earlier function map; OQ-I026-3 is the same question seen from the stepper).
; The lists are named by index in the pointer table (80 words), the leaves by address; they keep their auto names.
